"""Offline evaluation of the running ToggleBank policy agent, created from code.

Each dataset row is sent to the backend's /api/chat endpoint, so the real
triage -> specialist -> brand-voice flow answers it. Two criteria grade each row:

- offline-answer-quality: an OpenAI-backed LaunchDarkly judge config
- routed-to-expected-specialist: a local scorer that checks the specialist in
  the response's agentFlow against the row's metadata.expected_specialist

The AI SDK creates the evaluation and run through the LaunchDarkly REST API and
reports every score as an SDK event; LaunchDarkly stores the pass/fail verdict.

Usage (from the repo root, with the backend running):
    cd evals && uv run python run_policy_agent_eval.py --env-file ../.env.staging
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys
import urllib.request
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from dotenv import load_dotenv
from launchdarkly_ai_openai_messages import create_openai_messages_handler
from launchdarkly_ai_server import DatasetRow, Judge, Scorer, init_evaluations, shutdown

# The app's .env uses LAUNCHDARKLY_* names; the AI SDK reads LD_* names.
ENV_MAP = {
    "LD_API_TOKEN": "LAUNCHDARKLY_ACCESS_TOKEN",
    "LD_SDK_KEY": "LAUNCHDARKLY_SDK_KEY",
    "LD_API_BASE_URI": "LAUNCHDARKLY_API_HOST",
    "LD_UI_BASE_URI": "LAUNCHDARKLY_API_HOST",
    "LD_STREAM_URI": "LAUNCHDARKLY_STREAM_URI",
    "LD_EVENTS_URI": "LAUNCHDARKLY_EVENTS_URI",
}

# The agent route for each row, keyed by the rendered input, so the scorer
# (which only receives the row and the output text) can check routing.
routes: dict[str, list[str]] = {}


def chat_url() -> str:
    return os.getenv("POLICY_AGENT_URL", "http://localhost:8000").rstrip("/") + "/api/chat"


def post_chat(user_input: str) -> dict[str, Any]:
    body = json.dumps({"userInput": user_input, "userName": "Demo User"}).encode()
    request = urllib.request.Request(
        chat_url(), data=body, headers={"Content-Type": "application/json"}
    )
    with urllib.request.urlopen(request, timeout=180) as response:
        return json.loads(response.read())


async def policy_agent_handler(
    config: dict[str, Any],
    user_input: str | None = None,
    tool_handlers: dict[str, Any] | None = None,
    variables: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Generation handler: ask the running policy agent instead of calling a model."""
    del config, tool_handlers, variables
    reply = await asyncio.to_thread(post_chat, user_input or "")
    if reply.get("error"):
        raise RuntimeError(f"policy agent error: {reply['error']}")
    routes[user_input or ""] = [step.get("agent", "") for step in reply.get("agentFlow") or []]
    return {"output": reply.get("response") or ""}


def score_routing(row: DatasetRow, output: str | None) -> float:
    """1.0 when the expected specialist appears in the row's agent route."""
    del output
    expected = (row.metadata or {}).get("expected_specialist")
    return 1.0 if expected and expected in routes.get(row.input or "", []) else 0.0


async def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--env-file", default="../.env.staging")
    parser.add_argument("--dataset", default=os.getenv("LD_DATASET_KEY", "policy_agent_dataset"))
    parser.add_argument("--judge", default="offline-answer-quality")
    args = parser.parse_args()

    load_dotenv(Path(args.env_file))
    for target, source in ENV_MAP.items():
        if not os.getenv(target) and os.getenv(source):
            os.environ[target] = os.environ[source]
    missing = [name for name in ("LD_API_TOKEN", "LD_SDK_KEY", "OPENAI_API_KEY") if not os.getenv(name)]
    if missing:
        print(f"error: set {', '.join(missing)} (or the LAUNCHDARKLY_* equivalents)", file=sys.stderr)
        return 1

    project_key = os.environ["LAUNCHDARKLY_PROJECT_KEY"]
    unique = datetime.now(UTC).strftime("%Y%m%d-%H%M%S")
    print(f"project={project_key} dataset={args.dataset} agent={chat_url()}")

    evals = init_evaluations()
    try:
        result = await evals.run(
            project_key=project_key,
            key=f"policy-agent-offline-{unique}",
            dataset=args.dataset,
            handler=policy_agent_handler,
            judge_handlers=[create_openai_messages_handler()],
            generation={
                "provider": "custom",
                "model": "policy-agent-api",
                "instructions": "Generated by the running ToggleBank policy agent (/api/chat).",
            },
            criteria=[
                Judge(key=args.judge, threshold=0.7),
                Scorer(name="routed-to-expected-specialist", fn=score_routing, threshold=1.0),
            ],
            concurrency=2,
            poll_timeout_seconds=600,
        )
    finally:
        await shutdown()

    for row_input, route in routes.items():
        print(f"route: {' -> '.join(route)}  <- {row_input}")
    print(f"run_id={result.run_id}")
    print(f"url={result.url}")
    print(f"summary={result.summary}")
    print(f"stored_verdict={'passed' if result.passed else 'failed'}")
    return 0 if result.passed else 1


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
